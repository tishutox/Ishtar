-- Run once in Supabase Dashboard -> SQL Editor.
-- Creates public profiles, editable profile content, links, mentions and banners.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null,
  display_name text not null default '',
  bio text not null default '',
  bio_alignment text not null default 'left',
  avatar_url text,
  banner_url text,
  profile_background_color text not null default '#FFFFFF',
  profile_accent_color text not null default '#5860C3',
  keep_memories boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_username_format check (username ~ '^[A-Za-z0-9._-]{1,20}$'),
  constraint profiles_display_name_length check (char_length(display_name) <= 50),
  constraint profiles_bio_length check (char_length(bio) <= 5000),
  constraint profiles_bio_alignment check (
    bio_alignment in ('left', 'center', 'right', 'justify')
  )
);

alter table public.profiles
add column if not exists profile_background_color text not null default '#FFFFFF';

alter table public.profiles
add column if not exists profile_accent_color text not null default '#5860C3';

alter table public.profiles
add column if not exists keep_memories boolean not null default true;

create unique index if not exists profiles_username_lower_unique
on public.profiles (lower(username));

create table if not exists public.profile_links (
  id bigint generated by default as identity primary key,
  profile_id uuid not null references public.profiles(id) on delete cascade,
  label text not null,
  url text not null,
  platform text not null default 'legacy',
  username text not null default '',
  position integer not null default 0,
  constraint profile_links_label_length check (char_length(label) between 1 and 50),
  constraint profile_links_url_length check (char_length(url) between 1 and 2048)
);

alter table public.profile_links
add column if not exists platform text not null default 'legacy';

alter table public.profile_links
add column if not exists username text not null default '';

update public.profile_links
set username = label
where username = '';

do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'profiles_background_color_format'
  ) then
    alter table public.profiles add constraint profiles_background_color_format
    check (profile_background_color ~ '^#[0-9A-Fa-f]{6}$');
  end if;
  if not exists (
    select 1 from pg_constraint where conname = 'profiles_accent_color_format'
  ) then
    alter table public.profiles add constraint profiles_accent_color_format
    check (profile_accent_color ~ '^#[0-9A-Fa-f]{6}$');
  end if;
  if not exists (
    select 1 from pg_constraint where conname = 'profile_links_platform_value'
  ) then
    alter table public.profile_links add constraint profile_links_platform_value
    check (platform in (
      'instagram', 'x', 'twitch', 'youtube', 'discord', 'behance',
      'dribbble', 'github', 'bluesky', 'facebook', 'reddit', 'xbox',
      'playstation', 'nintendo', 'steam', 'vkontakte', 'pinterest', 'legacy'
    ));
  end if;
  if not exists (
    select 1 from pg_constraint where conname = 'profile_links_username_length'
  ) then
    alter table public.profile_links add constraint profile_links_username_length
    check (char_length(username) between 1 and 100);
  end if;
end
$$;

create table if not exists public.profile_mentions (
  id bigint generated by default as identity primary key,
  profile_id uuid not null references public.profiles(id) on delete cascade,
  mentioned_profile_id uuid not null references public.profiles(id) on delete cascade,
  custom_tag text not null,
  position integer not null default 0,
  constraint profile_mentions_not_self check (profile_id <> mentioned_profile_id),
  constraint profile_mentions_tag_length check (char_length(custom_tag) between 1 and 15),
  constraint profile_mentions_unique unique (profile_id, mentioned_profile_id)
);

delete from public.profile_mentions
where id in (
  select id
  from (
    select
      id,
      row_number() over (
        partition by profile_id
        order by position, id
      ) as mention_rank
    from public.profile_mentions
  ) ranked_mentions
  where mention_rank > 1
);

create unique index if not exists profile_mentions_one_per_profile
on public.profile_mentions (profile_id);

create or replace function public.set_profile_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists profiles_set_updated_at on public.profiles;
create trigger profiles_set_updated_at
before update on public.profiles
for each row execute function public.set_profile_updated_at();

create or replace function public.handle_new_user_profile()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  candidate_username text;
begin
  candidate_username := coalesce(
    nullif(new.raw_user_meta_data ->> 'username', ''),
    'user_' || left(new.id::text, 8)
  );

  begin
    insert into public.profiles (id, username, display_name, avatar_url)
    values (
      new.id,
      candidate_username,
      coalesce(nullif(new.raw_user_meta_data ->> 'display_name', ''), 'Amatsumara member'),
      nullif(new.raw_user_meta_data ->> 'avatar_url', '')
    )
    on conflict (id) do nothing;
  exception when unique_violation then
    insert into public.profiles (id, username, display_name, avatar_url)
    values (
      new.id,
      left(candidate_username, 11) || '_' || left(new.id::text, 8),
      coalesce(nullif(new.raw_user_meta_data ->> 'display_name', ''), 'Amatsumara member'),
      nullif(new.raw_user_meta_data ->> 'avatar_url', '')
    )
    on conflict (id) do nothing;
  end;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile
after insert on auth.users
for each row execute function public.handle_new_user_profile();

with existing_users as (
  select
    id,
    raw_user_meta_data,
    coalesce(nullif(raw_user_meta_data ->> 'username', ''), 'user_' || left(id::text, 8)) as base_username,
    row_number() over (
      partition by lower(coalesce(nullif(raw_user_meta_data ->> 'username', ''), 'user_' || left(id::text, 8)))
      order by created_at, id
    ) as username_rank
  from auth.users
)
insert into public.profiles (id, username, display_name, avatar_url)
select
  id,
  case
    when username_rank = 1 then base_username
    else left(base_username, 11) || '_' || left(id::text, 8)
  end,
  coalesce(nullif(raw_user_meta_data ->> 'display_name', ''), 'Amatsumara member'),
  nullif(raw_user_meta_data ->> 'avatar_url', '')
from existing_users
on conflict (id) do update set
  avatar_url = coalesce(public.profiles.avatar_url, excluded.avatar_url);

